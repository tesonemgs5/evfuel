-- =====================================================================
-- SCRIPT DATABASE SUPABASE - EVFUEL (registro ricariche)
-- =====================================================================
-- Esegui in Supabase: SQL Editor -> incolla -> Run.
-- L'app usa la chiave anon senza login, quindi le policy sono per anon.
-- =====================================================================

CREATE TABLE IF NOT EXISTS public.ricariche (
    id          BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    data        DATE NOT NULL,
    luogo       TEXT,
    km          NUMERIC,
    km_parziali NUMERIC,
    pct_prima   NUMERIC,
    pct_dopo    NUMERIC,
    kwh_eff     NUMERIC,
    kwh_teor    NUMERIC,
    prezzo_kwh  NUMERIC,
    costo       NUMERIC,
    kwh_100     NUMERIC,
    created_at  TIMESTAMP WITH TIME ZONE NOT NULL DEFAULT timezone('utc'::text, now())
);

CREATE INDEX IF NOT EXISTS ricariche_data_idx ON public.ricariche (data);
CREATE INDEX IF NOT EXISTS ricariche_km_idx   ON public.ricariche (km);

ALTER TABLE public.ricariche ENABLE ROW LEVEL SECURITY;

DROP POLICY IF EXISTS "evfuel_accesso_completo" ON public.ricariche;
CREATE POLICY "evfuel_accesso_completo"
ON public.ricariche
FOR ALL
TO anon, authenticated
USING (true)
WITH CHECK (true);
